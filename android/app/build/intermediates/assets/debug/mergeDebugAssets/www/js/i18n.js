  function t(key, vars) {
    var d = STR[lang] || STR.en;
    var s = d[key] !== undefined ? d[key] : (STR.en[key] !== undefined ? STR.en[key] : key);
    if (vars) {
      for (var k in vars) s = s.split('{' + k + '}').join(vars[k]);
    }
    return s;
  }

  function setLang(l) {
    lang = (l === 'hi') ? 'hi' : 'en';
    try { document.documentElement.lang = lang === 'hi' ? 'hi' : 'en'; } catch (e) {}
    var els = document.querySelectorAll('[data-i18n]');
    for (var i = 0; i < els.length; i++) {
      var k = els[i].getAttribute('data-i18n');
      if (els[i].tagName === 'INPUT' && els[i].type === 'text') els[i].placeholder = t(k);
      else els[i].textContent = t(k);
    }
  }

  function getLang() { return lang; }
